/// نتيجة جلب تخطيط الرئيسيّة — **ثلاث حالات لا اثنتان**.
///
/// ‼️ **لماذا لا يكفي `Map?`؟** لأنّ `null` كانت تعني «حُذفت الرئيسيّة» و«الشبكة
/// مقطوعة» معاً، والسلوك المطلوب في الحالتين **متعاكس**:
///
/// - حُذفت من اللوحة ⇒ يجب أن يعود الجهاز إلى **الرئيسيّة الرسميّة** المكتوبة
///   في التطبيق، وأن يُمحى المخزَّن. وإبقاؤها يعني صفحةً حذفها المالك تبقى
///   تعمل على أجهزة الناس بلا حدٍّ زمنيّ — ومنها روابط لأقسامٍ وعروضٍ انتهت.
/// - انقطعت الشبكة ⇒ يجب أن **يبقى** المعروض. ومحوُه يعني أنّ من رأى تخطيط
///   اللوحة يُرمى إلى الرئيسيّة القديمة لمجرّد أنّ الاتّصال تعثّر لحظة.
///
/// فالحالتان لا تُجمعان في قيمةٍ واحدة مهما بدت متشابهتين في الشيفرة.
enum HomeLayoutStatus {
  /// وصل تخطيطٌ صالحٌ فيه أقسامٌ تعرضها هذه النسخة.
  ok,

  /// **الخادم قال لا** — لا رئيسيّة منشورة لقناة `app` (404)، أو وصلت صفحةٌ بلا
  /// قسمٍ واحدٍ تعرضه هذه النسخة. حكمٌ قاطع ⇒ امحُ المخزَّن وارجع إلى الرسميّة.
  none,

  /// **لم يصل جواب** — انقطاع أو خطأ خادم أو جسمٌ تالف. لا حكم ⇒ أبقِ المعروض.
  unavailable,
}

class HomeLayoutFetch {
  const HomeLayoutFetch._(this.status, this.raw);

  const HomeLayoutFetch.ok(Map<String, dynamic> raw)
      : this._(HomeLayoutStatus.ok, raw);

  const HomeLayoutFetch.none() : this._(HomeLayoutStatus.none, null);

  const HomeLayoutFetch.unavailable()
      : this._(HomeLayoutStatus.unavailable, null);

  final HomeLayoutStatus status;

  /// الخام كما وصل — غير فارغ حين `ok` وحدها.
  ///
  /// ‼️ خامٌ لا `CmsPageModel`: يُخزَّن نصّاً، وحارس `minAppVersion` يجب أن
  /// يُعاد تطبيقه عند كلّ قراءة لا أن يُجمَّد في الكاش.
  final Map<String, dynamic>? raw;
}
